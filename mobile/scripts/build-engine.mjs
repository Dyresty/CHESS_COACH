// Builds the HTML page that runs Stockfish inside a hidden WebView.
// The engine's .js and .wasm are inlined so the page needs no files or network access.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const require = createRequire(import.meta.url)
const bin = join(dirname(require.resolve('stockfish/package.json')), 'bin')
const js = readFileSync(join(bin, 'stockfish-19-lite-single.js'), 'utf8')
const wasm = readFileSync(join(bin, 'stockfish-19-lite-single.wasm')).toString('base64')

// The page relays engine output in batches: info lines are only kept until the search ends,
// so the bridge carries one message per search instead of dozens.
const page = `<!doctype html><html><head><meta charset="utf-8"></head><body><script>
(function () {
  // In the app the page lives in a WebView; on the web build it lives in an iframe.
  var post = function (m) {
    var s = JSON.stringify(m);
    if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(s);
    else parent.postMessage({ chessCoachEngine: s }, '*');
  };
  try {
    var bytes = Uint8Array.from(atob(window.__WASM__), function (c) { return c.charCodeAt(0); });
    var wasmUrl = URL.createObjectURL(new Blob([bytes], { type: 'application/wasm' }));
    var jsUrl = URL.createObjectURL(new Blob([window.__ENGINE__], { type: 'text/javascript' }));
    var worker = new Worker(jsUrl + '#' + encodeURIComponent(wasmUrl));
    var info = {};
    worker.onmessage = function (e) {
      var line = String(e.data);
      if (line.indexOf('info') === 0 && line.indexOf(' pv ') > 0) {
        var m = / multipv (\\d+)/.exec(line);
        info[m ? m[1] : '1'] = line;
      } else if (line.indexOf('bestmove') === 0) {
        var lines = Object.keys(info).sort().map(function (k) { return info[k]; });
        info = {};
        post({ type: 'result', lines: lines, bestmove: line });
      } else if (line === 'readyok') {
        post({ type: 'ready' });
      }
    };
    worker.onerror = function (e) { post({ type: 'error', message: String(e.message || e) }); };
    window.__send = function (cmds) { for (var i = 0; i < cmds.length; i++) worker.postMessage(cmds[i]); };
    worker.postMessage('uci');
    worker.postMessage('isready');
  } catch (err) {
    post({ type: 'error', message: String(err) });
  }
})();
</script></body></html>`

const html = page.replace('<script>', `<script>window.__WASM__=${JSON.stringify(wasm)};window.__ENGINE__=${JSON.stringify(js)};</script><script>`)
writeFileSync(
  new URL('../src/engine/engineHtml.generated.ts', import.meta.url),
  `// Generated by scripts/build-engine.mjs. Do not edit or commit.\nexport const ENGINE_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`Wrote engine page (${Math.round(html.length / 1024)} KB)`)
