// Converts the cburnett piece set (as shipped in react-chessboard) to plain SVG strings for react-native-svg.
// Run from the repo root after `npm install`: node mobile/scripts/build-pieces.mjs
import { writeFileSync } from 'node:fs'
import { defaultPieces } from 'react-chessboard'

const camelToKebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

function serialise(el) {
  if (el == null || typeof el === 'boolean') return ''
  if (Array.isArray(el)) return el.map(serialise).join('')
  const { children, style, ...rest } = el.props
  const attrs = { ...rest, ...(style ?? {}) }
  delete attrs.width
  delete attrs.height
  const attrText = Object.entries(attrs)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k === 'xmlns' || k === 'version' || k === 'viewBox' || k === 'd' || k === 'transform' ? k : camelToKebab(k)}="${v}"`)
    .join(' ')
  return `<${el.type} ${attrText}>${serialise(children)}</${el.type}>`
}

const out = {}
for (const [key, render] of Object.entries(defaultPieces)) out[key] = serialise(render())
writeFileSync(
  new URL('../src/ui/pieceSvgs.ts', import.meta.url),
  `// Generated by scripts/build-pieces.mjs from the cburnett piece set (GPL/BSD/GFDL, via react-chessboard). Do not edit.\n` +
    `export const PIECE_SVGS: Record<string, string> = ${JSON.stringify(out, null, 2)}\n`,
)
console.log('Wrote', Object.keys(out).length, 'pieces')
